/*
 * Runtime String Deobfuscation
 *
 * Strings stored as XOR-encrypted byte arrays (key 0x55).
 * Decrypted on the stack at runtime, zeroed after use.
 * Defeats `strings` and static YARA rules.
 */

#include <windows.h>

#define STR_XOR_KEY 0x55

static __inline void deobf(char *out, const unsigned char *enc, int len) {
    for (int i = 0; i < len; i++)
        out[i] = (char)(enc[i] ^ STR_XOR_KEY);
}

